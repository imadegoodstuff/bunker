// Copy the compiled ABIs into the SDK as `as const` TypeScript so viem can type them.
const { readFileSync, writeFileSync, mkdirSync } = require("node:fs");
const { join } = require("node:path");

const root = join(__dirname, "..");
const outDir = join(root, "..", "sdk", "src", "abi");
mkdirSync(outDir, { recursive: true });

const contracts = [
  ["ShieldedPool", "contracts/ShieldedPool.sol/ShieldedPool.json"],
  ["Launchpad", "contracts/Launchpad.sol/Launchpad.json"],
  ["LaunchToken", "contracts/LaunchToken.sol/LaunchToken.json"],
  ["IERC20Metadata", "contracts/interfaces.sol/IERC20Metadata.json"],
  ["IPancakeRouter02", "contracts/interfaces.sol/IPancakeRouter02.json"],
  ["IPancakePair", "contracts/interfaces.sol/IPancakePair.json"],
];

const names = [];
for (const [name, rel] of contracts) {
  const art = JSON.parse(readFileSync(join(root, "artifacts", rel), "utf8"));
  const body = `// Generated by contracts/scripts/export-abi.cjs — do not edit.\nexport const ${name}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
  writeFileSync(join(outDir, `${name}.ts`), body);
  names.push(name);
}
writeFileSync(join(outDir, "index.ts"), names.map((n) => `export { ${n}Abi } from "./${n}.js";`).join("\n") + "\n");
console.log(`[abi] wrote ${names.length} ABIs to ${outDir}`);
