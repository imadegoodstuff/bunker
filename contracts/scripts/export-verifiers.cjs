// Exports the Groth16 verifying keys of the circuits as Solidity verifiers.
//
// Reads  circuits/build/<name>/<name>_dev.zkey   (the deterministic dev setup; see circuits/scripts/setup-dev.mjs)
// Writes contracts/contracts/verifiers/<Name>Verifier.sol
//
// The zkey the app serves (deploy/Dockerfile.app) and the zkey the verifier is
// exported from must be the same file, or every proof fails on-chain. CI
// regenerates both from the pinned ptau and diffs the committed verifiers.
const { readFileSync, writeFileSync, mkdirSync, existsSync } = require("node:fs");
const { join, resolve } = require("node:path");
const snarkjs = require("snarkjs");

const repo = resolve(__dirname, "..", "..");
const circuits = process.argv.slice(2).length ? process.argv.slice(2) : ["transact2x2", "transact4x2"];
const outDir = join(__dirname, "..", "contracts", "verifiers");
mkdirSync(outDir, { recursive: true });

(async () => {
  for (const name of circuits) {
    const zkey = join(repo, "circuits", "build", name, `${name}_dev.zkey`);
    if (!existsSync(zkey)) throw new Error(`missing ${zkey}: run \`npm -w circuits run build\` and \`node circuits/scripts/setup-dev.mjs\` first`);
    const vk = await snarkjs.zKey.exportVerificationKey(zkey);
    if (JSON.stringify(vk.vk_delta_2) === JSON.stringify(vk.vk_gamma_2)) throw new Error(`${name}: delta == gamma, phase-2 skipped; refusing to export a forgeable key`);
    const template = readFileSync(join(repo, "node_modules", "snarkjs", "templates", "verifier_groth16.sol.ejs"), "utf8");
    let sol = await snarkjs.zKey.exportSolidityVerifier(zkey, { groth16: template });
    const contractName = name === "transact2x2" ? "Transact2x2Verifier" : name === "transact4x2" ? "Transact4x2Verifier" : `${name}Verifier`;
    sol = sol.replace(/contract Groth16Verifier/, `contract ${contractName}`).replace(/pragma solidity [^;]+;/, "pragma solidity ^0.8.20;");
    sol = `// Generated by contracts/scripts/export-verifiers.cjs from circuits/build/${name}/${name}_dev.zkey. Do not edit.\n` + sol;
    const out = join(outDir, `${contractName}.sol`);
    writeFileSync(out, sol);
    console.log(`[verifiers] wrote ${out} (${vk.nPublic} public inputs)`);
  }
  process.exit(0);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
