// Converts snarkjs verification_key.json into the Rust constant layout used by
// groth16-solana (big-endian coordinates, G2 as (x1, x0, y1, y0)).
//
// Usage: node export-vk.mjs [circuit...]
// Reads  circuits/build/<name>/<name>_vk.json
// Writes programs/scash_vault/src/vk/<name>.rs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const repo = resolve(root, "..");
const circuits = process.argv.slice(2).length ? process.argv.slice(2) : ["transact2x2", "transact4x2"];

const P = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;

function be32(x) {
  let v = BigInt(x);
  const out = [];
  for (let i = 0; i < 32; i++) {
    out.unshift(Number(v & 0xffn));
    v >>= 8n;
  }
  return out;
}
function g1(p) {
  return [...be32(p[0]), ...be32(p[1])];
}
function g2(p) {
  // snarkjs: [[x0, x1], [y0, y1]] ; arkworks/EVM expect imaginary part first
  return [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])];
}
function fmt(bytes, indent = "    ") {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(indent + bytes.slice(i, i + 16).map((b) => b.toString().padStart(3)).join(", ") + ",");
  }
  return lines.join("\n");
}

for (const name of circuits) {
  const vk = JSON.parse(readFileSync(join(root, "build", name, `${name}_vk.json`), "utf8"));
  if (vk.curve !== "bn128" || vk.protocol !== "groth16") throw new Error("unexpected vk");
  const delta = JSON.stringify(vk.vk_delta_2);
  const gamma = JSON.stringify(vk.vk_gamma_2);
  if (delta === gamma) {
    throw new Error(`${name}: delta_g2 == gamma_g2, phase-2 was skipped. Refusing to export a forgeable key.`);
  }
  const nPublic = vk.nPublic;
  const ic = vk.IC.map(g1);
  let rs = `// Generated by circuits/scripts/export-vk.mjs from ${name}_vk.json. Do not edit.\n`;
  rs += `#![allow(clippy::all)]\nuse groth16_solana::groth16::Groth16Verifyingkey;\n\n`;
  rs += `pub const NR_PUBLIC_INPUTS: usize = ${nPublic};\n\n`;
  rs += `pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {\n`;
  rs += `    nr_pubinputs: ${nPublic},\n`;
  rs += `    vk_alpha_g1: [\n${fmt(g1(vk.vk_alpha_1), "        ")}\n    ],\n`;
  rs += `    vk_beta_g2: [\n${fmt(g2(vk.vk_beta_2), "        ")}\n    ],\n`;
  rs += `    vk_gamme_g2: [\n${fmt(g2(vk.vk_gamma_2), "        ")}\n    ],\n`;
  rs += `    vk_delta_g2: [\n${fmt(g2(vk.vk_delta_2), "        ")}\n    ],\n`;
  rs += `    vk_ic: &[\n`;
  for (const p of ic) rs += `        [\n${fmt(p, "            ")}\n        ],\n`;
  rs += `    ],\n};\n`;
  const out = join(repo, "programs", "scash_vault", "src", "vk", `${name}.rs`);
  writeFileSync(out, rs);
  console.log(`[vk] wrote ${out} (${nPublic} public inputs, ${ic.length} IC points)`);
}
